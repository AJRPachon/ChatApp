<#
.SYNOPSIS
  Takes the QA accounts out of the groups that earlier runs created (del*, grpedit*, qagrp*...).
.DESCRIPTION
  Flows create groups named <prefix><RUN_ID>. "Delete conversation" in the app only removes the
  row from Room (known bug), so those groups come back on the next sync and pile up in QA's list,
  pushing the 1:1 chat with QA2 below the FABs. This script signs in as each QA account (anon key
  from local.properties, credentials from .maestro/.env) and removes its own participant row from
  every group whose name matches a run-generated pattern: the same call as "Leave group" in the app
  (GroupRemoteSource.removeMember). The persistent QA_GROUP is never touched.
.EXAMPLE
  ./cleanup-qa-groups.ps1
  ./cleanup-qa-groups.ps1 -WhatIf     # only list what would be left
#>
param([switch]$WhatIf)
. "$PSScriptRoot/common.ps1"

$vars = Read-MaestroEnv
$supabase = $vars['SUPABASE_URL'].TrimEnd('/')
$anonKey = (Get-Content (Join-Path $PSScriptRoot '../../local.properties') -Encoding UTF8 |
    Where-Object { $_ -match '^\s*SUPABASE_ANON_KEY\s*=' } | Select-Object -First 1) -replace '^\s*SUPABASE_ANON_KEY\s*=\s*', ''
if (-not $supabase -or -not $anonKey) { throw 'Faltan SUPABASE_URL (.maestro/.env) o SUPABASE_ANON_KEY (local.properties)' }

# Group names generated by flows: a fixed prefix followed by a 14-digit RUN_ID.
$runGroup = '^(del|grpedit|grpadd|qagrp|grp|Temp ?)\d{14}$'

foreach ($n in '', '2', '3') {
    $mail = $vars["QA${n}_EMAIL"]; $pass = $vars["QA${n}_PASSWORD"]
    if (-not $mail -or -not $pass) { continue }
    $body = @{ email = $mail; password = $pass } | ConvertTo-Json
    $session = Invoke-RestMethod -Method Post -Uri "$supabase/auth/v1/token?grant_type=password" `
        -Headers @{ apikey = $anonKey } -ContentType 'application/json' -Body $body
    $h = @{ apikey = $anonKey; Authorization = "Bearer $($session.access_token)" }
    $uid = $session.user.id
    # RLS only returns the conversations this user takes part in.
    # Windows PowerShell returns the JSON array as a single object: unroll it before filtering.
    $groups = @((Invoke-RestMethod -Uri "$supabase/rest/v1/conversations?select=id,name&is_group=eq.true" -Headers $h) |
        ForEach-Object { $_ } | Where-Object { $_.name -cmatch $runGroup -and $_.name -ne $vars['QA_GROUP'] })
    Write-Host "QA$n ($($vars["QA${n}_USERNAME"])): $($groups.Count) grupos de ejecuciones anteriores"
    foreach ($g in $groups) {
        if ($WhatIf) { Write-Host "  (sale de) $($g.name)"; continue }
        Invoke-RestMethod -Method Delete -Headers $h `
            -Uri "$supabase/rest/v1/conversation_participants?conversation_id=eq.$($g.id)&user_id=eq.$uid" | Out-Null
    }
}
